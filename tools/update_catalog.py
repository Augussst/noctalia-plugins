#!/usr/bin/env python3
"""Regenerate catalog.toml from every <plugin>/plugin.toml in this repo.

Noctalia's git plugin sources list plugins from catalog.toml, so it must
always match the manifests. Run it locally, or let the GitHub Action do it
on every push to main:

    python3 tools/update_catalog.py

Timestamps come from git history, so the output only changes when a plugin
really changes:
  added_at    the commit that first added the plugin's plugin.toml
  updated_at  the first commit in which plugin.toml had its current version
Uncommitted plugins fall back to the current time.
"""

import subprocess
import sys
import time
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "catalog.toml"

REQUIRED = ("id", "name", "version", "author", "plugin_api", "tags")
OPTIONAL = ("license", "icon", "description", "deprecated")
ORDER = ("id", "name", "version", "updated_at", "added_at", "author", "license",
         "icon", "description", "plugin_api", "deprecated", "tags")


def git(*args: str) -> str:
    result = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else ""


def manifest_history(rel: str) -> list[tuple[int, str]]:
    """(commit time, version) for every commit touching rel, oldest first."""
    history = []
    for line in git("log", "--reverse", "--format=%H %ct", "--", rel).splitlines():
        sha, ct = line.split()
        try:
            version = tomllib.loads(git("show", f"{sha}:{rel}")).get("version")
        except tomllib.TOMLDecodeError:
            version = None
        history.append((int(ct), version))
    return history


def plugin_entry(manifest_path: Path) -> dict:
    rel = manifest_path.relative_to(ROOT).as_posix()
    with manifest_path.open("rb") as f:
        manifest = tomllib.load(f)

    missing = [k for k in REQUIRED if k not in manifest]
    if missing:
        raise SystemExit(f"{rel}: missing {', '.join(missing)}")
    folder = manifest_path.parent.name
    if manifest["id"].split("/", 1)[-1] != folder:
        raise SystemExit(f"{rel}: id {manifest['id']!r} does not end in the folder name {folder!r}")

    entry = {k: manifest[k] for k in REQUIRED}
    entry.update({k: manifest[k] for k in OPTIONAL if k in manifest})

    now = int(time.time())
    history = manifest_history(rel)
    entry["added_at"] = history[0][0] if history else now
    entry["updated_at"] = next((ct for ct, v in history if v == manifest["version"]), now)
    return entry


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    text = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{text}"'


def render(entries: list[dict]) -> str:
    blocks = ["# Generated by tools/update_catalog.py from each plugin.toml. Do not edit by hand."]
    for entry in entries:
        lines = ["[[plugin]]"]
        lines += [f"{k} = {toml_value(entry[k])}" for k in ORDER if k in entry]
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


def main() -> int:
    manifests = sorted(ROOT.glob("*/plugin.toml"))
    if not manifests:
        raise SystemExit("no */plugin.toml found")
    entries = sorted((plugin_entry(m) for m in manifests), key=lambda e: e["id"])
    text = render(entries)
    old = CATALOG.read_text() if CATALOG.exists() else ""
    if text == old:
        print("catalog.toml is up to date")
        return 0
    CATALOG.write_text(text)
    print(f"catalog.toml updated ({len(entries)} plugins)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
